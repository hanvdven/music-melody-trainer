// #1025 (Han 2026-08-17, "ik heb 3 tracks: water hum, water glockenspiel, en water percussion...!
// gebruik de instrumenten die tussen haakjes staan"): parses src/songs/world_midis/water sounds.mid
// (exported from Han's Reaper project `src/assets/ASSET DROP/bird sounds.rpp`) into 3 NAMED layers —
// unlike generate-bird-sounds.mjs (every track is an interchangeable unison layer on ONE instrument),
// each water track here is a DIFFERENT musical part on a DIFFERENT instrument, so tracks are matched
// by name rather than treated as a uniform pool. Reuses the exact same onset/offset -> app-tick +
// chord-grouping + velocity->volume conversion as generate-bird-sounds.mjs (§6c/§6d — one canonical
// MIDI->Melody conversion, not two).
//
// Run with: node scripts/generate-water-sounds.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parseMidi } from 'midi-file';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MIDI_PATH = path.join(__dirname, '..', 'src', 'songs', 'world_midis', 'water sounds.mid');
const OUT_PATH = path.join(__dirname, '..', 'src', 'model', 'waterSoundsManifest.generated.js');

const TICKS_PER_WHOLE = 48;   // src/constants/timing.js — kept in sync by hand (plain Node script, no import access)
const NOTE_NAMES = ['C', 'C♯', 'D', 'D♯', 'E', 'F', 'F♯', 'G', 'G♯', 'A', 'A♯', 'B'];

function midiNoteToName(midiNumber) {
    const octave = Math.floor(midiNumber / 12) - 1;
    const degree = midiNumber % 12;
    return `${NOTE_NAMES[degree]}${octave}`;
}

// Same conversion as generate-bird-sounds.mjs's trackToLayer: MIDI ticks -> app ticks, groups
// simultaneous notes into chord slots, velocity -> volumes[i] (0-1 fraction).
function trackToLayer(events, midiTicksPerQuarter) {
    const ticksPerAppTick = midiTicksPerQuarter / (TICKS_PER_WHOLE / 4);
    const toAppTicks = (midiTicks) => Math.max(1, Math.round(midiTicks / ticksPerAppTick));

    let cursor = 0;
    const openNotes = new Map();
    const rawNotes = [];
    for (const ev of events) {
        cursor += ev.deltaTime;
        if (ev.type === 'noteOn' && ev.velocity > 0) {
            openNotes.set(ev.noteNumber, { onset: cursor, velocity: ev.velocity });
        } else if (ev.type === 'noteOff' || (ev.type === 'noteOn' && ev.velocity === 0)) {
            const open = openNotes.get(ev.noteNumber);
            if (open != null) {
                rawNotes.push({ onset: open.onset, offset: cursor, noteNumber: ev.noteNumber, velocity: open.velocity });
                openNotes.delete(ev.noteNumber);
            }
        }
    }

    const byOnset = new Map();
    for (const n of rawNotes) {
        if (!byOnset.has(n.onset)) byOnset.set(n.onset, []);
        byOnset.get(n.onset).push(n);
    }
    const slots = [...byOnset.entries()].sort(([a], [b]) => a - b);

    const notes = [], durations = [], offsets = [], volumes = [];
    for (const [onset, group] of slots) {
        const startTick = toAppTicks(onset);
        const endTick = toAppTicks(Math.max(...group.map((n) => n.offset)));
        const pitches = group.map((n) => n.noteNumber).sort((a, b) => a - b).map(midiNoteToName);
        const avgVelocity = group.reduce((sum, n) => sum + n.velocity, 0) / group.length;
        notes.push(pitches.length > 1 ? pitches : pitches[0]);
        durations.push(Math.max(1, endTick - startTick));
        offsets.push(startTick);
        volumes.push(Math.round((avgVelocity / 127) * 1000) / 1000);
    }
    return { notes, durations, offsets, volumes };
}

// Reaper's own export names each track after its Reaper track name (see bird sounds.rpp: "water
// (percussion-standard)", "water hum (viola - hold ad infinitum)", "water (glockenspiel)") — matched
// by substring so a minor rename in Reaper (e.g. dropping "- hold ad infinitum") doesn't silently
// break this script.
const TRACK_MATCHERS = {
    waterPercussion: (name) => /percussion/i.test(name),
    waterHum: (name) => /hum/i.test(name),
    waterGlockenspiel: (name) => /glockenspiel/i.test(name),
};

function main() {
    const input = fs.readFileSync(MIDI_PATH);
    const parsed = parseMidi(input);
    const layersByKey = {};
    for (const track of parsed.tracks) {
        const nameEvent = track.find((e) => e.type === 'trackName');
        const trackName = nameEvent?.text ?? '';
        const hasNotes = track.some((e) => e.type === 'noteOn' && e.velocity > 0);
        if (!hasNotes) continue;
        const matchedKey = Object.entries(TRACK_MATCHERS).find(([, test]) => test(trackName))?.[0];
        if (!matchedKey) {
            console.warn(`Unmatched track "${trackName}" — skipped (add a TRACK_MATCHERS entry if this is a new water layer).`);
            continue;
        }
        layersByKey[matchedKey] = trackToLayer(track, parsed.header.ticksPerBeat);
    }

    const out = `// AUTO-GENERATED by scripts/generate-water-sounds.mjs — do not hand-edit.
// Re-run the script after replacing src/songs/world_midis/water sounds.mid.
// #1025: the 3 water layers (matched by Reaper track name — see TRACK_MATCHERS), each as a plain
// { notes, durations, offsets, volumes } quadruplet in this app's own tick units (TICKS_PER_WHOLE=48)
// — same shape/conversion as birdSoundsManifest.generated.js. Tempo-agnostic; rescales to whatever
// bpm useWorldAmbientMusic.js plays it at. waterPercussion has no instrument yet (#1037, blocked on a
// GM percussion kit source).
export const WATER_SOUND_LAYERS = ${JSON.stringify(layersByKey, null, 2)};
`;
    fs.writeFileSync(OUT_PATH, out);
    console.log(`Wrote ${OUT_PATH} —`, Object.fromEntries(Object.entries(layersByKey).map(([k, v]) => [k, v.notes.length + ' notes'])));
}

main();
