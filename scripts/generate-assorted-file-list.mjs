// #955 (boot-slowness initiative, Han 2026-08-13, "let's go for the robust solution"): a HAR
// capture of a real boot showed ~1100 of 1606 requests were individual PNG module resolutions
// from bestiaryAssets.js/characterAssets.js's eager `import.meta.glob(..., { eager: true, query:
// '?url' })` calls — each glob-matched file becomes its own dev-server HTTP round-trip BEFORE
// React can render anything (ES module semantics require every static import to resolve first).
// Moving the underlying PNGs to public/ (a plain static file server, outside Vite's module graph
// entirely) eliminates that per-file request cost — the URL is just a fixed string, fetched only
// when something actually renders that sprite. But public/ isn't visible to import.meta.glob (Vite
// doesn't scan directories outside src/ for module resolution), so the RUNTIME code that used to
// discover "which files exist" via the glob's own keys needs a different source of truth: this
// script, run offline, walks public/ASSORTED/characters and public/ASSORTED/fx once and writes a
// flat manifest of relative paths. bestiaryAssets.js/characterAssets.js then reconstruct the exact
// same {relPath: url} shape the old glob produced from this list (see their own comments) — every
// downstream consumer (regex extraction, categorization) needed zero changes as a result.
//
// Run with: node scripts/generate-assorted-file-list.mjs (re-run after adding/removing/renaming
// any file under public/ASSORTED/characters or public/ASSORTED/fx).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', 'public', 'ASSORTED');
const SCAN_DIRS = ['characters', 'fx'];

function walk(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(abs, out);
    } else if (entry.isFile() && /\.png$/i.test(entry.name)) {
      out.push(path.relative(ROOT, abs).split(path.sep).join('/'));
    }
  }
}

const files = [];
for (const sub of SCAN_DIRS) {
  const dir = path.join(ROOT, sub);
  if (fs.existsSync(dir)) walk(dir, files);
}
files.sort();

const outPath = path.resolve(__dirname, '..', 'src', 'model', 'assortedFileList.generated.js');
const header = `// AUTO-GENERATED by scripts/generate-assorted-file-list.mjs from public/ASSORTED/{characters,fx}.
// Do not hand-edit — re-run the script to regenerate.
`;
const body = `export const ASSORTED_FILES = ${JSON.stringify(files, null, 2)};\n`;
fs.writeFileSync(outPath, header + body);

console.log(`Wrote ${files.length} paths to ${outPath}`);
