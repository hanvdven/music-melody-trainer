// One-time mirror of the OLD 'woodblock' sound (Han 2026-08-20, restoring pre-#955 timbre).
//
// #955 (offline-boot initiative) moved every melodic instrument slug — including 'woodblock',
// which is the metronome's default instrument AND the sound behind the wh/wm/wl percussion pads
// (they share the same `instruments.metronome` Soundfont instance, see drumKits.js's
// METRONOME_NOTE_IDS / KIT_NOTE_MAPPINGS comment) — from smplr's online CDN
// (gleitz.github.io/midi-js-soundfonts, MusyngKite kit, smplr's DEFAULT_SOUNDFONT_KIT) to samples
// extracted from Han's own local FluidR3_GM.sf2 (scripts/extract-soundfont-samples.mjs). FluidR3_GM
// and MusyngKite are different soundfont sets with different woodblock recordings, so the switch
// was an audible regression Han didn't ask for and only noticed after the fact.
//
// This script fetches the EXACT old CDN data once — the MusyngKite kit's own MIDI.js-format
// woodblock file, which (unlike the single-C4 FluidR3 extraction) already has a real recording for
// all 88 semitones A0-C8 — decodes each embedded MP3 to raw PCM, and writes it to
// public/samples/Instruments/woodblock-classic/ as local WAV files, alongside a manifest consumed
// by localInstruments.js. Deliberately a SEPARATE folder/manifest from the FluidR3 'woodblock'
// entry in localInstrumentBuffers.generated.js (that file is regenerated wholesale by the other
// script and must not be hand-edited — see its own header). Dev-only, run manually; not part of
// the app bundle/runtime, matching extract-soundfont-samples.mjs's own convention.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { MPEGDecoder } from 'mpg123-decoder';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'public/samples/Instruments/woodblock-classic');
const MANIFEST_PATH = path.join(ROOT, 'src/audio/legacyWoodblockBuffers.generated.js');

const SOUNDFONT_URL = 'https://gleitz.github.io/midi-js-soundfonts/MusyngKite/woodblock-mp3.js';

function writeWav(filePath, pcm16, sampleRate) {
  const numChannels = 1;
  const bytesPerSample = 2;
  const blockAlign = numChannels * bytesPerSample;
  const dataSize = pcm16.length * bytesPerSample;
  const buffer = Buffer.alloc(44 + dataSize);
  buffer.write('RIFF', 0);
  buffer.writeUInt32LE(36 + dataSize, 4);
  buffer.write('WAVE', 8);
  buffer.write('fmt ', 12);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20); // PCM
  buffer.writeUInt16LE(numChannels, 22);
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * blockAlign, 28);
  buffer.writeUInt16LE(blockAlign, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write('data', 36);
  buffer.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < pcm16.length; i++) {
    buffer.writeInt16LE(pcm16[i], 44 + i * 2);
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, buffer);
}

function floatTo16BitPCM(float32) {
  const out = new Int16Array(float32.length);
  for (let i = 0; i < float32.length; i++) {
    const s = Math.max(-1, Math.min(1, float32[i]));
    out[i] = s < 0 ? s * 0x8000 : s * 0x7fff;
  }
  return out;
}

console.log('Fetching', SOUNDFONT_URL, '...');
const res = await fetch(SOUNDFONT_URL);
if (!res.ok) throw new Error(`Fetch failed: ${res.status} ${res.statusText}`);
const source = await res.text();

const m = source.match(/MIDI\.Soundfont\.woodblock\s*=\s*(\{[\s\S]*\});?\s*$/);
if (!m) throw new Error('Could not find MIDI.Soundfont.woodblock object in fetched file');
let jsonStr = m[1].trim();
if (jsonStr.endsWith(';')) jsonStr = jsonStr.slice(0, -1);
jsonStr = jsonStr.replace(/,(\s*\})/g, '$1'); // trailing comma before closing brace isn't valid JSON
const noteToDataUrl = JSON.parse(jsonStr);
const noteNames = Object.keys(noteToDataUrl);
console.log('Found', noteNames.length, 'notes:', noteNames.join(' '));

const decoder = new MPEGDecoder();
await decoder.ready;

const buffers = {};
for (const noteName of noteNames) {
  const dataUrl = noteToDataUrl[noteName];
  const base64 = dataUrl.slice(dataUrl.indexOf(',') + 1);
  const mp3Bytes = Buffer.from(base64, 'base64');
  const { channelData, sampleRate, errors } = decoder.decode(new Uint8Array(mp3Bytes));
  if (errors.length) {
    console.warn(`${noteName}: decode warnings —`, errors.map((e) => e.message).join('; '));
  }
  const pcm16 = floatTo16BitPCM(channelData[0]); // mono, matches extract-soundfont-samples.mjs convention
  writeWav(path.join(OUT_DIR, `${noteName}.wav`), pcm16, sampleRate);
  buffers[noteName] = { file: noteName };
}
decoder.free();

const header = `// AUTO-GENERATED by scripts/extract-legacy-woodblock.mjs from the MusyngKite CDN's own woodblock
// recordings (gleitz.github.io/midi-js-soundfonts) — a one-time offline mirror of the pre-#955
// woodblock sound. Do not hand-edit — re-run the script to regenerate. See localInstruments.js.
`;
const body = `export const LEGACY_WOODBLOCK_BUFFERS = ${JSON.stringify(buffers, null, 2)};\n`;
fs.writeFileSync(MANIFEST_PATH, header + body);

console.log('\nDone.', noteNames.length, 'sample files written to', OUT_DIR);
console.log('Manifest written to', MANIFEST_PATH);
