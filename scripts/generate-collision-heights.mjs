// #1040 (Han 2026-08-17, "ik heb een collision mask geplaatst... bij de boomstam zijn nu wat diagonale
// vlakken waar het personage over moet wandelen"): the Collision_mask LDtk layer places tiles from a
// small hand-drawn tileset (collsion-mask.png) where EACH TILE'S OWN PIXEL SILHOUETTE encodes a ground
// height profile — per 16px-wide tile, per pixel-column, the topmost OPAQUE pixel row is the local ground
// surface height (row 0 = flush with the tile's top edge = highest ground; row 15 = almost the tile's
// bottom edge = lowest; no opaque pixel at all = no override at that exact column). This one-time
// generator decodes that image into a static lookup, the same "derive from the real asset instead of
// hand-typing a table" approach already used for soundfont sample extraction / normal-map generation
// (CLAUDE.md §6c) — confirmed with Han (2026-08-17 interview): "topmost opaque pixel per column = the
// walking surface height... lower row number = higher ground" and "fully-transparent column -> fall back
// to the flat 32px rule there".
//
// Run with: node scripts/generate-collision-heights.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { PNG } from 'pngjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PNG_PATH = path.join(__dirname, '..', 'src', 'assets', 'ASSORTED', 'tiles', 'tiles', 'collsion-mask.png');
const OUT_PATH = path.join(__dirname, '..', 'src', 'model', 'collisionMaskHeights.generated.js');
const TILE_SIZE = 16;
const OPAQUE_ALPHA_THRESHOLD = 10;   // matches the exploratory analysis pass done during the #1040 interview

function main() {
    const png = PNG.sync.read(fs.readFileSync(PNG_PATH));
    const cols = png.width / TILE_SIZE;
    const rows = png.height / TILE_SIZE;
    const heights = {};
    for (let r = 0; r < rows; r++) {
        for (let c = 0; c < cols; c++) {
            const tileId = r * cols + c;
            const colHeights = [];
            for (let x = 0; x < TILE_SIZE; x++) {
                let top = -1;
                for (let y = 0; y < TILE_SIZE; y++) {
                    const pxIndex = ((r * TILE_SIZE + y) * png.width + (c * TILE_SIZE + x)) * 4;
                    if (png.data[pxIndex + 3] > OPAQUE_ALPHA_THRESHOLD) { top = y; break; }
                }
                colHeights.push(top);
            }
            heights[tileId] = colHeights;
        }
    }

    const out = `// AUTO-GENERATED by scripts/generate-collision-heights.mjs — do not hand-edit.
// Re-run the script after replacing src/assets/ASSORTED/tiles/tiles/collsion-mask.png.
// #1040: per-tile-ID, per-16px-column ground height within the Collision_mask tileset. \`heights[tileId][x]\`
// (x in 0..15) is the topmost OPAQUE pixel row (0-15, 0=highest ground/tile's own top edge) at that
// column, or -1 if the column has no opaque pixel (falls back to STAND_HEIGHT_PX — see groundHeightAt in
// RpgLevelPanel.jsx). Tile ID = row * COLLISION_TILE_COLS + col, matching LDtk's own \`src\` [x,y] tile-sheet
// position (tileId = (src[1]/16) * COLLISION_TILE_COLS + (src[0]/16)).
export const COLLISION_TILE_HEIGHTS = ${JSON.stringify(heights, null, 2)};
export const COLLISION_TILE_COLS = ${cols};
`;
    fs.writeFileSync(OUT_PATH, out);
    console.log(`Wrote ${OUT_PATH} — ${rows * cols} tiles (${cols} cols x ${rows} rows).`);
}

main();
